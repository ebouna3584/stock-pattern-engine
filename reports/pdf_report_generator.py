def _price_chart(df: pd.DataFrame, res: TickerAnalysis) -> bytes:
    try:
        dates  = _safe_dates(df)
        closes = pd.to_numeric(df["close"], errors="coerce")
        n      = len(df)

        fig, ax = plt.subplots(figsize=(9.5, CHART_MAIN / inch))
        fig.patch.set_facecolor(M["bg"])
        ax.set_facecolor(M["bg"])

        # Price line
        ax.plot(dates, closes, color=M["price"], linewidth=1.4, label="Close", zorder=3)

        # Fill under price
        ax.fill_between(dates, closes, closes.min() * 0.995,
                        alpha=0.06, color=M["price"])

        # Best-fit regression overlay
        x_num = np.arange(len(closes))
        valid_mask = ~np.isnan(closes.values)
        if valid_mask.sum() >= 10:
            try:
                coeffs = np.polyfit(x_num[valid_mask], closes.values[valid_mask], 1)
                y_reg = np.polyval(coeffs, x_num)
                ax.plot(dates, y_reg, color=M["regression"], linewidth=1.0,
                        linestyle="-.", alpha=0.6, label="Linear fit", zorder=3)
            except Exception:
                pass

        # Overlay trendlines from top pattern
        tp = res.top_pattern
        if tp:
            # Support line
            ax.annotate("", xy=(dates.iloc[-1], tp.support_line.end_price),
                        xytext=(dates.iloc[0], tp.support_line.start_price),
                        arrowprops=dict(arrowstyle="-", color=M["support"],
                                       lw=1.4, linestyle="--"),
                        annotation_clip=False)
            ax.plot([dates.iloc[0], dates.iloc[-1]],
                    [tp.support_line.start_price, tp.support_line.end_price],
                    color=M["support"], linewidth=1.3, linestyle="--",
                    alpha=0.8, label="Support", zorder=4)
            # Resistance line
            ax.plot([dates.iloc[0], dates.iloc[-1]],
                    [tp.resistance_line.start_price, tp.resistance_line.end_price],
                    color=M["resistance"], linewidth=1.3, linestyle="--",
                    alpha=0.8, label="Resistance", zorder=4)
            # Breakout level
            ax.axhline(tp.breakout_level, color=M["breakout"], linewidth=1.0,
                       linestyle=":", alpha=0.9, label=f"Breakout ${tp.breakout_level:.2f}", zorder=4)

        ax.set_title(f"{res.ticker} — Price History (Close)",
                     fontsize=9.5, color=M["text"], fontweight="bold", pad=6)
        ax.set_ylabel("Price ($)", fontsize=7.5, color=M["axis"])
        ax.yaxis.set_major_formatter(mticker.FormatStrFormatter("$%.2f"))
        ax.legend(fontsize=6.5, loc="upper left", framealpha=0.75)
        ax.grid(True, color=M["grid"], linewidth=0.5, linestyle="--")
        for sp in ax.spines.values():
            sp.set_color(M["spine"]); sp.set_linewidth(0.6)
        ax.tick_params(colors=M["axis"], labelsize=7)
        _format_dates(ax, n)
        fig.tight_layout(pad=0.5)
        return _fig_to_png(fig)
    except Exception:
        return b""


def _volume_chart(df: pd.DataFrame, res: TickerAnalysis) -> bytes:
    try:
        dates   = _safe_dates(df)
        volumes = pd.to_numeric(df["volume"], errors="coerce").fillna(0)
        avg_vol = volumes.rolling(20, min_periods=1).mean()

        # Identify spike candles (>=1.5x avg)
        spikes = volumes >= avg_vol * 1.5
        bar_colors = [M["vol_spike"] if s else M["volume"] for s in spikes]

        fig, ax = plt.subplots(figsize=(9.5, CHART_IND / inch))
        fig.patch.set_facecolor(M["bg"])
        ax.set_facecolor(M["bg"])

        ax.bar(dates, volumes / 1e6, color=bar_colors, width=0.6, alpha=0.85)
        ax.plot(dates, avg_vol / 1e6, color=M["price"], linewidth=0.9,
                linestyle="--", label="20-bar avg", alpha=0.7)

        ax.set_title(f"{res.ticker} — Volume (M shares)", fontsize=9.5,
                     color=M["text"], fontweight="bold", pad=6)
        ax.set_ylabel("Volume (M)", fontsize=7.5, color=M["axis"])
        ax.legend(fontsize=6.5, loc="upper left", framealpha=0.75)
        ax.grid(True, color=M["grid"], linewidth=0.5, linestyle="--")
        for sp in ax.spines.values():
            sp.set_color(M["spine"]); sp.set_linewidth(0.6)
        ax.tick_params(colors=M["axis"], labelsize=7)
        _format_dates(ax, len(df))
        fig.tight_layout(pad=0.5)
        return _fig_to_png(fig)
    except Exception:
        return b""


