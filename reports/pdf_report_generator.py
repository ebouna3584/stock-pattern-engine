def _make_page_callback(gen_time: str):
    def _on_page(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 6.5)
        canvas.setFillColor(C_MUTED)
        canvas.drawString(MARGIN, 0.42 * inch,
                          f"Stock Pattern Engine v{TEMPLATE_VERSION}  |  Generated: {gen_time}")
        canvas.drawRightString(PAGE_W - MARGIN, 0.42 * inch, f"Page {doc.page}")
        canvas.setFont("Helvetica-Oblique", 5.5)
        canvas.drawCentredString(PAGE_W / 2, 0.27 * inch, "Not financial advice. Educational use only.")
        canvas.restoreState()
    return _on_page


