def _pattern_overlay_chart(df: pd.DataFrame, res: TickerAnalysis) -> bytes:
    """Draw pattern-specific geometry on a zoomed price chart."""
    try:
        return _pattern_overlay_chart_inner(df, res)
    except Exception:
        return b""


def _pattern_overlay_chart_inner(df: pd.DataFrame, res: TickerAnalysis) -> bytes:
    tp = res.top_pattern
    if not tp:
        return b""

    dates  = _safe_dates(df)
    closes = pd.to_numeric(df["close"],  errors="coerce")
    highs  = pd.to_numeric(df["high"],   errors="coerce")
    lows   = pd.to_numeric(df["low"],    errors="coerce")
    n      = len(df)

    fig, ax = plt.subplots(figsize=(9.5, CHART_PATTERN / inch))
    fig.patch.set_facecolor(M["bg"])
    ax.set_facecolor(M["bg"])

    # Shade the pattern window with light fill
    try:
        s_idx = df[df["date"].astype(str) >= str(tp.start_date)].index[0]
    except Exception:
        s_idx = 0
    ax.axvspan(dates.iloc[s_idx], dates.iloc[-1],
               alpha=0.06, color=M["breakout"], label="Pattern window")

    # Price + wick candle-lite bars
    ax.plot(dates, closes, color=M["price"], linewidth=1.3,
            label="Close", zorder=3)
    ax.vlines(dates, lows, highs, color=M["grid"], linewidth=0.5,
              alpha=0.5, label="Hi/Lo range")

    ptype = tp.pattern_type.value

    # Draw support line
    ax.plot([dates.iloc[0], dates.iloc[-1]],
            [tp.support_line.start_price, tp.support_line.end_price],
            color=M["support"], linewidth=1.6, linestyle="--",
            alpha=0.85, label="Support", zorder=5)
    # Draw resistance line
    ax.plot([dates.iloc[0], dates.iloc[-1]],
            [tp.resistance_line.start_price, tp.resistance_line.end_price],
            color=M["resistance"], linewidth=1.6, linestyle="--",
            alpha=0.85, label="Resistance", zorder=5)

    # ── Pattern-specific overlays ─────────────────────────────────────────────

    if "cup" in ptype:
        # Polynomial U-curve overlay on lows
        x = np.arange(n, dtype=float)
        try:
            coeffs = np.polyfit(x, lows.values, 2)
            y_poly = np.polyval(coeffs, x)
            ax.plot(dates, y_poly, color=M["regression"],
                    linewidth=2.0, linestyle=":", label="Poly fit (cup)", zorder=6)
        except Exception:
            pass
        # Annotate cup and handle regions
        mid = n // 2
        ax.annotate("Cup", xy=(dates.iloc[mid], lows.min()),
                    xytext=(dates.iloc[mid], lows.min() - lows.std() * 0.8),
                    fontsize=7.5, color=M["regression"], fontweight="bold",
                    arrowprops=dict(arrowstyle="->", color=M["regression"], lw=0.8))
        if n > 10:
            ax.annotate("Handle", xy=(dates.iloc[-5], closes.iloc[-5]),
                        xytext=(dates.iloc[-8], closes.iloc[-8] - closes.std() * 0.5),
                        fontsize=7.5, color=M["breakout"], fontweight="bold",
                        arrowprops=dict(arrowstyle="->", color=M["breakout"], lw=0.8))

    elif "head_and_shoulders" in ptype or "inverse_head" in ptype:
        # Mark 3 peaks (or troughs for inverse)
        inv = "inverse" in ptype
        arr = lows.values if inv else highs.values
        prominence = arr.std() * 0.4
        if inv:
            pks, _ = find_peaks(-arr, distance=n // 6, prominence=prominence)
        else:
            pks, _ = find_peaks(arr, distance=n // 6, prominence=prominence)
        for i, pk in enumerate(pks[:3]):
            label_map = ["Left Shoulder", "Head", "Right Shoulder"]
            lbl = label_map[i] if i < 3 else ""
            y_pt = arr[pk]
            offset = -arr.std() * 0.5 if inv else arr.std() * 0.5
            ax.annotate(lbl, xy=(dates.iloc[pk], y_pt),
                        xytext=(dates.iloc[pk], y_pt + offset),
                        fontsize=6.5, color=M["breakout"], fontweight="bold",
                        ha="center",
                        arrowprops=dict(arrowstyle="->", color=M["breakout"], lw=0.7))

    elif "double" in ptype or "triple" in ptype:
        # Mark equal peaks / troughs
        inv = "bottom" in ptype
        arr = lows.values if inv else highs.values
        pks, _ = find_peaks(-arr if inv else arr,
                            distance=n // 8, prominence=arr.std() * 0.3)
        n_peaks = 2 if "double" in ptype else 3
        for pk in pks[:n_peaks]:
            ax.axvline(dates.iloc[pk], color=M["breakout"],
                       linewidth=0.9, linestyle=":", alpha=0.8)
            ax.annotate("Peak" if not inv else "Trough",
                        xy=(dates.iloc[pk], arr[pk]),
                        xytext=(dates.iloc[pk], arr[pk] + arr.std() * 0.4 * (1 if not inv else -1)),
                        fontsize=6, color=M["breakout"], ha="center",
                        arrowprops=dict(arrowstyle="->", color=M["breakout"], lw=0.6))

    elif "wedge" in ptype or "triangle" in ptype or "rectangle" in ptype or "flag" in ptype or "pennant" in ptype:
        # Lines already drawn via support/resistance above; add apex annotation
        apex_x = dates.iloc[-1]
        apex_y = (tp.support_line.end_price + tp.resistance_line.end_price) / 2
        ax.annotate("Apex →", xy=(apex_x, apex_y),
                    fontsize=7, color=M["breakout"], va="center",
                    fontweight="bold")

    # Breakout level
    ax.axhline(tp.breakout_level, color=M["breakout"], linewidth=1.2,
               linestyle=":", alpha=0.9,
               label=f"Breakout ${tp.breakout_level:.2f}", zorder=6)

    pattern_label = ptype.replace("_", " ").title()
    ax.set_title(
        f"{res.ticker} — Pattern: {pattern_label}  "
        f"(Confidence {tp.confidence_score:.0f}/100, {tp.trend_direction.value})",
        fontsize=9, color=M["text"], fontweight="bold", pad=6,
    )
    ax.set_ylabel("Price ($)", fontsize=7.5, color=M["axis"])
    ax.yaxis.set_major_formatter(mticker.FormatStrFormatter("$%.2f"))
    ax.legend(fontsize=6.5, loc="upper left", framealpha=0.75, ncol=2)
    ax.grid(True, color=M["grid"], linewidth=0.5, linestyle="--")
    for sp in ax.spines.values():
        sp.set_color(M["spine"]); sp.set_linewidth(0.6)
    ax.tick_params(colors=M["axis"], labelsize=7)
    _format_dates(ax, n)
    fig.tight_layout(pad=0.5)
    return _fig_to_png(fig)


