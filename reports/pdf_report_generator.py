def _indicator_panel_inner(df: pd.DataFrame, ticker: str) -> bytes:
    dates = _safe_dates(df)
    n     = len(df)

    has_rsi  = "RSI"  in df.columns
    has_macd = "MACD" in df.columns and "MACD_signal" in df.columns
    has_atr  = "ATR"  in df.columns

    n_panels = sum([has_rsi, has_macd, has_atr])
    if n_panels == 0:
        return b""

    ratios = []
    if has_rsi:  ratios.append(1.0)
    if has_macd: ratios.append(1.2)
