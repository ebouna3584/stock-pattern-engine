# ─── Main Entry Point ─────────────────────────────────────────────────────────

def generate_pdf_report(
    analysis_response: AnalysisResponse,
    dataframes: Dict[str, pd.DataFrame],
) -> bytes:
    """
    Generate a complete investor-grade PDF report.

    Args:
        analysis_response: The full AnalysisResponse from run_analysis().
        dataframes: Dict mapping ticker symbol → raw OHLCV+indicator DataFrame.

    Returns:
        PDF as raw bytes (ready for streaming HTTP response).
    """
    gen_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")
    page_callback = _make_page_callback(gen_time)

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=MARGIN,
        rightMargin=MARGIN,
        topMargin=MARGIN,
        bottomMargin=0.75 * inch,
        title=f"Stock Pattern Engine Report — {gen_time}",
        author="Stock Pattern Engine v1.0.0",
        subject="Technical Analysis Report",
    )

    ST = _styles()
    elements: list = []

    # 1. Cover
    _build_cover(elements, analysis_response, ST, gen_time=gen_time)

    # 2. Executive Summary
    _build_executive_summary(elements, analysis_response, ST)

    # 3. Per-ticker sections
    for res in analysis_response.results:
        ticker = res.ticker
        df = dataframes.get(ticker, dataframes.get(ticker.upper(), pd.DataFrame()))
        if df.empty:
            elements.append(Paragraph(
                f"No raw data available for {ticker}.", ST["body"]
            ))
            elements.append(PageBreak())
            continue
        _build_ticker_section(elements, res, df.copy(), ST)

    # 4. Education page
    _build_education_page(elements, ST)

    doc.build(elements, onFirstPage=page_callback, onLaterPages=page_callback)
    buf.seek(0)
    return buf.read()


__all__ = ["generate_pdf_report"]
