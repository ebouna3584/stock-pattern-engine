def _fig_to_png(fig: plt.Figure) -> bytes:
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=DPI, bbox_inches="tight",
                facecolor=fig.get_facecolor())
    buf.seek(0)
    data = buf.read()
    plt.close(fig)
    return data


def _png_to_rl(png: bytes, width: float, height: Optional[float] = None) -> RLImage:
    img = RLImage(io.BytesIO(png))
    aspect = img.drawHeight / img.drawWidth
    img.drawWidth  = width
    img.drawHeight = height if height else width * aspect
    return img


def _mpl_base(nrows=1, ratios=None, h_total=3.3) -> tuple:
    """Create a styled figure with 1-3 subplots sharing the x-axis."""
    fig, axes = plt.subplots(
        nrows, 1,
        figsize=(9.5, h_total),
        gridspec_kw={"height_ratios": ratios or [1] * nrows},
        sharex=(nrows > 1),
    )
    if nrows == 1:
        axes = [axes]
    for ax in axes:
        ax.set_facecolor(M["bg"])
        ax.grid(True, color=M["grid"], linewidth=0.6, linestyle="--", alpha=0.8)
        ax.tick_params(colors=M["axis"], labelsize=7)
        for sp in ax.spines.values():
            sp.set_color(M["spine"])
            sp.set_linewidth(0.6)
    fig.patch.set_facecolor(M["bg"])
    fig.subplots_adjust(hspace=0.08)
    return fig, axes


def _format_dates(ax, n: int):
    if n <= 30:
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%b %d"))
    elif n <= 120:
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%b '%y"))
    else:
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))
    plt.setp(ax.get_xticklabels(), rotation=30, ha="right", fontsize=6)


def _safe_dates(df: pd.DataFrame) -> pd.Series:
    return pd.to_datetime(df["date"], errors="coerce")


